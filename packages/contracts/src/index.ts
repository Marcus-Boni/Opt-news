// Endpoints

type Method = "GET" | "POST" | "PUT" | "PATCH";
export interface Endpoint {
  method: Method;
  path: string;
  summary: string;
  params?: z.ZodObject;
  query?: z.ZodObject;
  body?: z.ZodType;
  /** undefined: 204 No Content. */
  response?: z.ZodType;
  status?: 200 | 201;
  /** public: no session needed. Everything else requires a session; finer rules live in the server policy. */
  access?: "public";
}

// Curation (NX-03, N-11, Q-10): what the pipeline held back or sent to review, curator decisions and the labels that
// calibrate the selection gates.
export const CURATION_VERDICTS = ["should_publish", "should_skip"] as const;
export const CurationItem = z.object({
  id: Id,
  title: z.string(),
  url: z.string(),
  sourceId: z.string(),
  sourceName: z.string(),
  tier: SourceTier,
  status: z.enum(SOURCE_ITEM_STATUS),
  scores: z.tuple([z.int(), z.int()]).nullable(),
  /** The gate the active model holds this tier to (two scores must add up to twice this). */
  threshold: z.int(),
  reason: z.string().nullable(),
  publishedAt: Instant.nullable(),
  observedAt: Instant,
  storyId: Id.nullable(),
  forced: z.boolean(),
  /** Submitted by a member (N-11). */
  submittedBy: z.string().nullable(),
  myVerdict: z.enum(CURATION_VERDICTS).nullable(),
  verdicts: z.object({ shouldPublish: z.int(), shouldSkip: z.int() }),
});
export const CurationReview = z.object({
  storyId: Id,
  headline: z.string(),
  summary: z.string().nullable(),
  sourceName: z.string(),
  url: z.string(),
  reviewReason: z.string().nullable(),
  editorialScore: z.number().nullable(),
  publishedAt: Instant.nullable(),
});
export const CurationSubmission = z.object({
  id: Id,
  url: z.string(),
  note: z.string().nullable(),
  submittedBy: z.string(),
  createdAt: Instant,
  error: z.string().nullable(),
});
export const CurationQueue = z.object({
  reviews: z.array(CurationReview),
  submissions: z.array(CurationSubmission),
  items: z.array(CurationItem),
});
export const CurationQuery = z.object({
  status: z.enum(["held", "selected", "all"]).default("held"),
});
export const ReviewDecision = z.object({
  decision: z.enum(["publish", "retract"]),
  note: z.string().trim().max(500).optional(),
});
export const ItemLabel = z.object({
  verdict: z.enum(CURATION_VERDICTS),
  note: z.string().trim().max(500).optional(),
});
export const Calibration = z.object({
  model: z.string(),
  labels: z.int(),
  /** Labels the pipeline agreed with: should_publish on a selected item, should_skip on one kept out. */
  agreed: z.int(),
  missed: z.int(),
  extra: z.int(),
  byTier: z.array(
    z.object({
      tier: SourceTier,
      threshold: z.int(),
      labels: z.int(),
      /** Score sums (a + b) of labelled items: the gate separates them when every skip sits below every publish. */
      lowestShouldPublish: z.int().nullable(),
      highestShouldSkip: z.int().nullable(),
      /** A gate between the two when they separate; null while the labels overlap or one side is missing. */
      suggested: z.int().nullable(),
    }),
  ),
});

