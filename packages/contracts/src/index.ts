// Operations

/** Health of one source in the curation pipeline (N-01: curators see failures without reading logs). */
export const SOURCE_TIERS = ["T1", "T1_5", "T2"] as const;
export const SourceTier = z.enum(SOURCE_TIERS);

export const SourceStatus = z.object({
  id: z.string(),
  name: z.string(),
  tier: SourceTier,
  /**
   * rss = collected feed; web_list = a listing page without a feed, whose article links start with linkPrefix
   * (ADR-0015); submission = links members submit (N-11), never fetched as a feed.
   */
  kind: z.enum(["rss", "web_list", "submission"]),
  linkPrefix: z.string().nullable(),
  /** Selection threshold of the tier: two scores must add up to twice this. */
  threshold: z.int(),
  active: z.boolean(),
  feedUrl: z.string(),
  intervalMinutes: z.int(),
  /** ADR-0008: only headline, feed excerpt and link until a source has a legal basis for more (Q-02). */
  licensePolicy: z.enum(["summary_link"]),
  lastAttemptAt: Instant.nullable(),
  lastSuccessAt: Instant.nullable(),
  lastError: z.string().nullable(),
  /** Raw items by pipeline state. */
  items: z.object({
    pending: z.int(),
    selected: z.int(),
    notSelected: z.int(),
    rejected: z.int(),
    archived: z.int(),
    failed: z.int(),
  }),
  published: z.int(),
  underReview: z.int(),
  /** Items collected on each of the last 7 days (São Paulo calendar), oldest first; today is the last entry. */
  week: z.array(z.int()).length(7),
});
export type SourceStatus = z.infer<typeof SourceStatus>;

/** What the team did each day (São Paulo calendar), oldest first; today is the last entry. */
export const Activity = z.object({
  days: z.array(z.object({ date: z.iso.date(), stories: z.int(), comments: z.int(), proposals: z.int() })),
});

export const SOURCE_ITEM_STATUS = ["discovered", "archived", "rejected", "not_selected", "selected", "failed"] as const;
export const SourceDetail = SourceStatus.extend({
  /** Latest items of this source and what the pipeline did with each (failures and rejections with their reason). */
  recent: z.array(
    z.object({
      id: Id,
      title: z.string(),
      url: z.string(),
      status: z.enum(SOURCE_ITEM_STATUS),
      error: z.string().nullable(),
      scores: z.tuple([z.int(), z.int()]).nullable(),
      publishedAt: Instant.nullable(),
      observedAt: Instant,
      storyId: Id.nullable(),
    }),
  ),
});
export type SourceDetail = z.infer<typeof SourceDetail>;

const Interval = z.int().min(5).max(1440);
export const SourceCreate = z.object({
  /** Stable slug; derived from the name when omitted. */
  id: z
    .string()
    .regex(/^[a-z0-9][a-z0-9-]{1,48}$/)
    .optional(),
  name: z.string().trim().min(3).max(120),
  /** The feed, or for web_list the listing page. */
  feedUrl: z.string().trim().min(8).max(2048),
  kind: z.enum(["rss", "web_list"]).default("rss"),
  /** web_list: only links starting with this become items; defaults to the listing address. */
  linkPrefix: z.string().trim().min(8).max(2048).optional(),
  tier: SourceTier,
  intervalMinutes: Interval.default(60),
});
/** Curators may pause/resume and change the cadence; name, addresses and tier are for admins (docs/09 RBAC). */
export const SourceUpdate = z.object({
  active: z.boolean().optional(),
  intervalMinutes: Interval.optional(),
  name: z.string().trim().min(3).max(120).optional(),
  feedUrl: z.string().trim().min(8).max(2048).optional(),
  linkPrefix: z.string().trim().min(8).max(2048).optional(),
  tier: SourceTier.optional(),
});

