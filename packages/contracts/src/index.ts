// HTTP contract of the Opt News API v1: the single source of truth for the API (validation, OpenAPI) and the web
// client (types). Upstream engine types (AIHOT) never appear here: they stay behind the API's adapter.
import { z } from "zod";

export const Id = z.uuid();
export const Instant = z.iso.datetime();

// Identity

export const ROLES = ["visitor", "member", "organizer", "curator", "admin"] as const;
export const Role = z.enum(ROLES);
export type Role = z.infer<typeof Role>;

export const MemberRef = z.object({ id: Id, displayName: z.string() });
export type MemberRef = z.infer<typeof MemberRef>;

/** What the signed-in member may do; computed by the server policy, used by the web only to show or hide actions. */
export const Capabilities = z.object({
  contribute: z.boolean(),
  organize: z.boolean(),
  moderate: z.boolean(),
  administer: z.boolean(),
});

export const Me = MemberRef.extend({ roles: z.array(Role), can: Capabilities, csrfToken: z.string() });
export type Me = z.infer<typeof Me>;

export const Persona = MemberRef.extend({ roles: z.array(Role), description: z.string() });
export const DevLogin = z.object({ memberId: Id });

// Content

export const Topic = z.object({ slug: z.string(), label: z.string() });
export type Topic = z.infer<typeof Topic>;

export const STORY_STATUS = ["published", "under_review", "retracted"] as const;

export const Counts = z.object({ comments: z.int(), proposals: z.int(), insights: z.int() });

/** N-06: the event a story belongs to; coverage = how many published stories cover it. */
export const EventRef = z.object({ id: Id, title: z.string(), coverage: z.int() });

export const StoryCard = z.object({
  id: Id,
  headline: z.string(),
  summary: z.string().nullable(),
  source: z.object({ name: z.string() }),
  originalUrl: z.url(),
  originalPublishedAt: Instant.nullable(),
  firstSeenAt: Instant,
  topics: z.array(z.string()),
  editorialScore: z.number().nullable(),
  /** Internal relevance is not calibrated yet (Q-10): always null until curators approve a policy. */
  optsolvRelevanceScore: z.number().nullable(),
  aiGenerated: z.boolean(),
  status: z.enum(STORY_STATUS),
  counts: Counts,
  event: EventRef.nullable(),
});
export type StoryCard = z.infer<typeof StoryCard>;

export const StoryRef = z.object({
  id: Id,
  headline: z.string(),
  source: z.object({ name: z.string() }),
  originalPublishedAt: Instant.nullable(),
  status: z.enum(STORY_STATUS),
});

export const ProposalSummary = z.object({ id: Id, title: z.string(), status: z.string(), votes: z.int() });
export const InsightSummary = z.object({ id: Id, title: z.string(), status: z.string() });

export const StoryDetail = StoryCard.extend({
  language: z.string(),
  /** Why the engine selected it. Generated by AI; shown as such. */
  selectionReason: z.string().nullable(),
  provenance: z.object({
    provider: z.string(),
    modelVersion: z.string().nullable(),
    policyVersion: z.string().nullable(),
    evidenceUrls: z.array(z.url()),
    syncedAt: Instant,
  }),
  retractedAt: Instant.nullable(),
  /** Every readable coverage of the same event, oldest first (includes this story). */
  event: z.object({ id: Id, title: z.string(), heatScore: z.number(), stories: z.array(StoryRef) }).nullable(),
  proposals: z.array(ProposalSummary),
  insights: z.array(InsightSummary),
});
export type StoryDetail = z.infer<typeof StoryDetail>;

export const STORY_SORT = ["recent", "relevance"] as const;
export const StoryQuery = z.object({
  topic: z.string().max(60).optional(),
  sort: z.enum(STORY_SORT).default("recent"),
  q: z.string().trim().max(200).optional(),
  from: Instant.optional(),
  to: Instant.optional(),
  cursor: z.string().max(200).optional(),
  limit: z.coerce.number().int().min(1).max(50).default(20),
});

export const Page = <T extends z.ZodType>(item: T) =>
  z.object({ items: z.array(item), nextCursor: z.string().nullable() });

export const SubmissionCreate = z.object({
  url: z.string().trim().min(8).max(2048),
  note: z.string().trim().max(500).optional(),
});
export const Submission = z.object({
  id: Id,
  normalizedUrl: z.string(),
  status: z.enum(["pending_review", "duplicate", "accepted", "rejected"]),
  storyId: Id.nullable(),
  createdAt: Instant,
});

export const EventDetail = z.object({
  id: Id,
  title: z.string(),
  heatScore: z.number(),
  lastUpdatedAt: Instant,
  /** Timeline of the coverage, oldest first. */
  stories: z.array(StoryCard),
});
export type EventDetail = z.infer<typeof EventDetail>;

/** N-07. The overview is machine-written; it is withdrawn when a story it summarised is no longer shown. */
export const Briefing = z.object({
  date: z.iso.date(),
  generatedAt: Instant,
  overview: z.string().nullable(),
  overviewWithdrawn: z.boolean(),
  sections: z.array(z.object({ label: z.string(), stories: z.array(StoryCard) })),
  modelVersion: z.string().nullable(),
  policyVersion: z.string(),
});
export type Briefing = z.infer<typeof Briefing>;
export const BriefingSummary = z.object({ date: z.iso.date(), generatedAt: Instant, items: z.int() });

// Community

export const TARGET_TYPES = ["story", "meetup", "insight"] as const;
export const TargetType = z.enum(TARGET_TYPES);

export const Comment = z.object({
  id: Id,
  targetType: TargetType,
  targetId: Id,
  parentId: Id.nullable(),
  author: MemberRef,
  /** null when hidden by moderation or deleted: the placeholder keeps the thread readable. */
  body: z.string().nullable(),
  status: z.enum(["visible", "hidden", "deleted"]),
  revision: z.int(),
  createdAt: Instant,
  editedAt: Instant.nullable(),
  moderationReason: z.string().nullable(),
});
export type Comment = z.infer<typeof Comment>;

export const CommentQuery = z.object({
  targetType: TargetType,
  targetId: Id,
  cursor: z.string().max(200).optional(),
  limit: z.coerce.number().int().min(1).max(100).default(50),
});
export const CommentCreate = z.object({
  targetType: TargetType,
  targetId: Id,
  parentId: Id.optional(),
  body: z.string().trim().min(1).max(4000),
});
export const CommentEdit = z.object({ body: z.string().trim().min(1).max(4000), revision: z.int() });
export const CommentModerate = z.object({
  action: z.enum(["hide", "restore"]),
  reason: z.string().trim().min(3).max(500),
});

export const Discussion = z.object({
  comment: Comment,
  target: z.object({ type: TargetType, id: Id, title: z.string() }),
});

// Meetups

